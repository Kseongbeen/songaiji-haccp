import pandas as pd

OUT = "output"

# ── ② 정부 문서에서 옮긴 값 ──────────────────────────────────────
컨설팅_예산 = {2019: 2800, 2020: 2800, 2021: 2593, 2022: 2593, 2023: 2033, 2024: 1015}  # 백만원, 국비+지방비+자부담
단가_한우 = 6.0   # 백만원. 한우·육우·육계·오리 등 개별 농장 컨설팅
단가_돼지 = 8.0   # 백만원. 돼지·젖소·산란계·종축장 등 개별 농장 컨설팅
단가_단체_농가 = 3.0  # 백만원. 단체 컨설팅은 단체당 기본 6.0 + 농가당 3.0
                      # 기본료를 빼고 농가당 3.0만으로 나눈 값이 단체 방식의 상한이다.
한육우_50이상 = 20763  # 가축동향조사 2026년 2분기, 한·육우 75,647 - 50마리 미만 54,884

로드맵 = [
    # 연차, 연도, 계획(추진계획 로드맵 그림), 실행(공고·보도), 농장_계획, 농장_실행, 규모
    (1, 2024, "집유장", "집유장", "", "", "2개소 · 187.5백만원"),
    (2, 2025, "도축장(소·돼지), 농장(젖소)", "도축장(포유류), 집유장", "젖소", "", "국비 551백만원 · 업체당 국비 40백만원"),
    (3, 2026, "도축장(가금), 농장(소·돼지·가금)", "가금류 도축장, 도축장·집유장 8개소", "소·돼지·가금", "", "구축비 1억 이내 최대 70%"),
]


def 부문별():
    h = pd.read_csv("data/haccp_인증업체_raw.csv", dtype=str)
    a = h[h["productGb"] == "축산물"].drop_duplicates("appointno")
    sm = pd.read_csv("data/smart_축산물.csv", dtype=str).drop_duplicates("appointno")
    s = sm["businesstype"].value_counts()
    t = a.groupby(["companykindNm", "businesstypeNm"]).size().rename("HACCP").to_frame()
    t["스마트"] = [int(s.get(b, 0)) for _, b in t.index]
    g = t.groupby(level=0).sum()

    cs = pd.read_csv("data/smart_기술지원.csv", dtype=str)
    f = cs["indutyNm"].fillna("")
    요청 = {
        "제조,가공": int((f.str.contains("식육포장|식육가공|유가공|알가공") ).sum()),
        # '운반'만 쓰면 식품제조가공업(운반급식) 3건이 섞인다. 축산물 업종명으로만 잡는다.
        "유통,판매,조리": int(f.str.contains("식육판매|식용란|축산물유통전문|식육즉석|축산물운반|축산물보관").sum()),
        "농장": int((f == "가축사육업").sum()) + int(f.str.contains("종축|부화").sum()),
        "사료": int(f.str.contains("사료").sum()),
    }
    g["기술지원요청"] = [요청.get(i, 0) for i in g.index]
    g["스마트전환%"] = (g["스마트"] / g["HACCP"] * 100).round(2)
    g["요청률%"] = (g["기술지원요청"] / g["HACCP"] * 100).round(2)
    g = g.reindex(["제조,가공", "유통,판매,조리", "사료", "농장"])
    g.index = ["축산물 가공", "축산물 유통·판매", "사료", "농장"]
    g.to_csv(OUT + "/축산스마트_부문별.csv", encoding="utf-8-sig")
    print("[부문별]")
    print(g.to_string())
    return g, len(cs)


def 예산():
    bu = pd.read_csv(OUT + "/부문별_연도별신규.csv", index_col=0)
    rows = []
    for y, b in 컨설팅_예산.items():
        rows.append({
            "연도": y, "컨설팅예산_백만원": b,
            "컨설팅가능농장_상한_한우단가": int(b // 단가_한우),
            "컨설팅가능농장_상한_돼지단가": int(b // 단가_돼지),
            "농장신규인증": int(bu.loc[y, "축산물 농장"]),
        })
    t = pd.DataFrame(rows)
    t.to_csv(OUT + "/축산스마트_예산.csv", index=False, encoding="utf-8-sig")
    print("\n[컨설팅 예산과 농장 신규 인증]")
    print(t.to_string(index=False))
    감소 = (1 - 컨설팅_예산[2024] / 컨설팅_예산[2019]) * 100
    print("  2019 -> 2024 예산 {:.0f}% 감소".format(감소))
    개별 = int(컨설팅_예산[2024] // 단가_한우)
    단체 = int(컨설팅_예산[2024] // 단가_단체_농가)
    print("  [기획서] 2024년 예산 전액을 한우에 쓴다고 가정하면")
    print("    개별 컨설팅(농장당 600만 원) {}곳 · 단체 컨설팅(농가당 300만 원, 기본료 제외) 최대 {}곳".format(개별, 단체))
    print("    50마리 이상 한·육우 {:,}곳 ÷ 연 {}곳 = {:.1f}년 이상".format(
        한육우_50이상, 단체, 한육우_50이상 / 단체))
    print("  주의: 예산에는 도축장·집유장·사료공장 컨설팅, 방역 컨설팅, 살모넬라 백신이 함께 들어 있다.")
    print("        그래서 '컨설팅 가능 농장'은 예산 전부를 농장에 썼을 때의 상한이다.")
    return t, 감소


if __name__ == "__main__":
    g, 요청전체 = 부문별()
    t, 감소 = 예산()

    pd.DataFrame(로드맵, columns=["연차", "연도", "계획", "실행", "농장_계획", "농장_실행", "규모"]) \
        .to_csv(OUT + "/축산스마트_로드맵.csv", index=False, encoding="utf-8-sig")
    print("\n[로드맵 계획 대비 실행]  계획 연차에 농장이 든 해: 2025(젖소), 2026(소·돼지·가금) / 실행: 0")

    가공유통 = g.loc[["축산물 가공", "축산물 유통·판매"]]
    벤치율 = 가공유통["기술지원요청"].sum() / 가공유통["HACCP"].sum() * 100
    농장 = g.loc["농장"]
    지표 = pd.DataFrame([{
        "농장_HACCP": int(농장["HACCP"]),
        "농장_스마트": int(농장["스마트"]),
        "농장_기술지원요청": int(농장["기술지원요청"]),
        "기술지원요청_전체": 요청전체,
        "가공유통_요청률%": round(벤치율, 2),
        "농장_요청률%": round(농장["기술지원요청"] / 농장["HACCP"] * 100, 3),
        "농장_벤치마크요청수": int(round(농장["HACCP"] * 벤치율 / 100)),
        "컨설팅예산_감소%": round(감소, 0),
        "2024_컨설팅가능농장_상한": "{}~{}".format(
            int(컨설팅_예산[2024] // 단가_돼지), int(컨설팅_예산[2024] // 단가_한우)),
        "2024_한우컨설팅_개별~단체": "{}~{}".format(
            int(컨설팅_예산[2024] // 단가_한우), int(컨설팅_예산[2024] // 단가_단체_농가)),
        "50마리이상_도달연수": round(한육우_50이상 / (컨설팅_예산[2024] // 단가_단체_농가), 1),
        "2024_농장신규": int(t.loc[t["연도"] == 2024, "농장신규인증"].iloc[0]),
    }])
    지표.to_csv(OUT + "/축산스마트_지표.csv", index=False, encoding="utf-8-sig")
    print("\n[핵심 지표]")
    print(지표.T.to_string(header=False))
