def 시도별(a):
    """시도별로 축종을 묶어 인증률을 낸다. 농장수가 적은 시도는 값이 튄다."""
    m = {"한우": "한·육우", "육우": "한·육우", "젖소": "젖소", "돼지": "돼지",
         "산란계": "닭", "육계": "닭", "오리": "오리"}
    a = a.copy()
    a["군"] = a["축종"].map(m)
    a = a.dropna(subset=["군"])

    import importlib.util
    _s = importlib.util.spec_from_file_location("v19", "19_매칭보정.py")
    v19 = importlib.util.module_from_spec(_s)
    _s.loader.exec_module(v19)
    a["시도보정"] = [v19.시도보정.get(str(x).strip(), str(x).strip()) for x in a["시도"]]

    # 농장키(원래 시도 표기)로 먼저 중복을 없앤 뒤, 보정한 시도로 묶는다.
    a = a.drop_duplicates(["군"] + 농장키)
    분자 = a.groupby(["시도보정", "군"]).size().unstack(fill_value=0)
    분모 = 시도농장.copy()
    분모["시도"] = 분모["시도"].map(lambda x: 통합.get(x, x))
    분모 = 분모.groupby("시도").sum()
    공통 = 분모.index.intersection(분자.index)
    빠짐 = sorted(set(분자.index) - set(공통))
    if 빠짐:
        print("\n  [주의] 분모 표에 없는 시도 표기 {}건: {}".format(len(빠짐), ", ".join(빠짐)))

    rows = []
    for 시도 in 분모.index:
        for 군 in ["한·육우", "젖소", "돼지", "닭", "오리"]:
            d = int(분모.loc[시도, 군])
            n = int(분자.loc[시도, 군]) if (시도 in 분자.index and 군 in 분자) else 0
            rows.append({"시도": 시도, "축종군": 군, "인증농가": n, "사육농장수": d,
                         "인증률%": round(n / d * 100, 1) if d else np.nan})
    t = pd.DataFrame(rows)
    t.to_csv(OUT + "/축종_시도.csv", index=False, encoding="utf-8-sig")

    print("\n" + "=" * 78)
    print(" 시도별 인증률(%)  — 사육 농장 30곳 미만인 칸은 비웠다. 한 곳만 받아도 값이 튄다.")
    print("=" * 78)
    p = t.copy()
    p.loc[p["사육농장수"] < 30, "인증률%"] = np.nan
    print(p.pivot(index="시도", columns="축종군", values="인증률%")
          .reindex(columns=["한·육우", "젖소", "돼지", "닭", "오리"])
          .to_string(na_rep="-"))
    넘침 = p[p["인증률%"] > 100]
    if len(넘침):
        print("\n  [100%를 넘는 칸이 있다 — 숨기지 않고 남긴다]")
        for _, r in 넘침.iterrows():
            print("    {} {} {:,}/{:,} = {:.1f}%".format(
                r["시도"], r["축종군"], int(r["인증농가"]),
                int(r["사육농장수"]), r["인증률%"]))
        print("    이건 오류가 아니라 위 한계 1·2가 눈에 보이는 자리다.")
        print("    산란계와 육계를 각각 받은 한 농가가 분자에서 두 번 세어지고,")
        print("    3천 마리 미만 농가는 분모에서 빠져 있다. 닭은 순위만 읽어야 한다.")

    print("\n[저장] output/축종_시도.csv")

    # 기획서 [그림 5]: 한·육우 농장 500곳 이상 시도를 농장 수 순으로
    h = (t[(t["축종군"] == "한·육우") & (t["사육농장수"] >= 500)]
         .sort_values("사육농장수", ascending=False)
         .rename(columns={"인증농가": "인증", "사육농장수": "농장", "인증률%": "인증률"})
         [["시도", "인증", "농장", "인증률"]])
    h.to_csv(OUT + "/한육우_시도별_인증률.csv", index=False, encoding="utf-8-sig")
    print("\n[한·육우 시도별]  기획서 [그림 5]")
    print(h.to_string(index=False))
    print("[저장] output/한육우_시도별_인증률.csv")
    return t


